# 1. Integer (int) - Whole numbers  
age = 25  
year = 2024  
print("Age:", age)  
print("Year:", year)  

# 2. Float (float) - Decimal numbers  
height = 5.9  
temperature = 98.6  
print("Height:", height, "feet")  
print("Temperature:", temperature, "°F")  

# 3. String (str) - Text data  
name = "Alice"  
greeting = "Hello, Python!"  
print("Name:", name)  
print("Greeting:", greeting)  

# 4. Boolean (bool) - True or False  
is_student = True  
has_job = False  
print("Is Student?", is_student)  
print("Has Job?", has_job)  

# 5. List (list) - Ordered, mutable collection  
fruits = ["apple", "banana", "cherry"]  
numbers = [1, 2, 3, 4, 5]  
print("Fruits:", fruits)  
print("Numbers:", numbers)  

# 6. Tuple (tuple) - Ordered, immutable collection  
coordinates = (10.5, 20.3)  
colors = ("red", "green", "blue")  
print("Coordinates:", coordinates)  
print("Colors:", colors)  

# 7. Dictionary (dict) - Key-value pairs  
person = {"name": "Bob", "age": 30, "city": "New York"}  
print("Person Details:", person)  

# 8. Set (set) - Unordered, unique elements  
unique_numbers = {1, 2, 2, 3, 4}  # Duplicates are removed  
print("Unique Numbers:", unique_numbers)  

# 9. Type Conversion Examples  
num_str = "100"  
num_int = int(num_str)  
print("String to Integer:", num_int)  

float_str = "3.14"  
float_num = float(float_str)  
print("String to Float:", float_num)  

# 10. Checking Variable Types  
print("Type of 'age':", type(age))  
print("Type of 'height':", type(height))  
print("Type of 'name':", type(name))  
